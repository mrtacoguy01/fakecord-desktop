VesktopNative.voice.onToggleSelfMute(() => VoiceActions.toggleSelfMute());
VesktopNative.voice.onToggleSelfDeaf(() => VoiceActions.toggleSelfDeaf());
VesktopNative.voice.onToggleVAD(() => {
    const voiceActions = VoiceActions as any;
    const mediaEngineStore = MediaEngineStore as any;

    const currentMode = mediaEngineStore?.getMode?.();
    const nextMode = currentMode === "PUSH_TO_TALK" ? "VOICE_ACTIVITY" : "PUSH_TO_TALK";

    if (typeof voiceActions?.setMode === "function") {
        voiceActions.setMode(nextMode);
        return;
    }
});

